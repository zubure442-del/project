import type { Phase } from './provider';

/**
 * Нативный pull-to-refresh на вкладках.
 *
 * Спиннер iOS не показываем вовсе: как только жест отработал, поверх вкладок открывается экран
 * загрузки — ход выгрузки виден там, а два индикатора сразу только мешают. Проблема была в
 * другом: жест прерывался появившимся сверху экраном, ScrollView не получал конца касания,
 * и растянутый контрол оставался висеть над содержимым до ручной прокрутки. Привязка `refreshing`
 * к общей фазе делу не помогла — контрол есть на КАЖДОЙ вкладке, и на неактивных он залипал ещё
 * охотнее (его было видно при переходе между вкладками).
 *
 * Поэтому контрол просто пересоздаётся: ключ меняется, когда загрузка началась и когда
 * закончилась ЛЮБЫМ способом — удача, свежий кэш, таймаут, обрыв. Новый нативный контрол
 * всегда собран, растянутым он остаться не может.
 */
export type RefreshKey = 'loading' | 'idle';

export const refreshControlKey = (phase: Phase): RefreshKey => (phase === 'loading' ? 'loading' : 'idle');

/** Показывать ли спиннер прямо сейчас. Всегда нет: прогресс живёт на экране загрузки. */
export const refreshIndicatorVisible = (): boolean => false;
