import { describe, expect, it } from 'vitest';
import { AI_ADVICE_MAX_CHARS, cleanAdvice, isSafeAdvice } from './ai-advice';

describe('СИНТЕТИЧЕСКИЕ: проверка «Мнения Лиса» от модели', () => {
  it('обычный совет проходит, кавычки и переводы строк убираются', () => {
    const text = cleanAdvice('«Ночь была короче обычной.\n\nСегодня держите темп спокойнее и ложитесь пораньше.»');
    expect(text).toBe('Ночь была короче обычной. Сегодня держите темп спокойнее и ложитесь пораньше.');
    expect(isSafeAdvice(text)).toBe(true);
  });

  it('диагнозы, врачи, обещания и чужие бренды — не показываем', () => {
    for (const bad of [
      'Похоже на признаки диабета, стоит сдать анализы и показаться специалисту.',
      'Обратитесь к врачу, если сон не наладится в ближайшие дни, это важно.',
      'Похоже на гипертонию, давление держится высоким уже второй день.',
      'Лекарства от давления сегодня лучше принять пораньше, как обычно.',
      'Отдохните как следует, и усталость пройдёт уже к вечеру, обещаем.',
      'Как советуют в Oura, ложитесь до полуночи и не пейте кофе вечером.',
      'Сон **важен**: ложитесь пораньше и не засиживайтесь с телефоном.',
    ]) {
      expect(isSafeAdvice(cleanAdvice(bad))).toBe(false);
    }
  });

  it('давление, сахар и кислород как процессы тела — можно (владелец 26.09), цифры — нет', () => {
    expect(isSafeAdvice('Давление сегодня держится выше обычного. Кажется, ночь вышла короче, чем нужно телу.')).toBe(true);
    expect(isSafeAdvice('Силы к вечеру тают. Похоже, сахар сегодня скакал сильнее обычного из-за перекусов.')).toBe(true);
    expect(isSafeAdvice('Сон был долгим, но разбитость есть. Ночью кислород в крови проседал ниже обычного.')).toBe(true);
    expect(isSafeAdvice('Давление сегодня около 135 — выше обычного, ночь была короткой.')).toBe(false);
  });

  it('слишком короткий или длинный текст — не совет', () => {
    expect(isSafeAdvice('Спите.')).toBe(false);
    expect(isSafeAdvice('Пройдитесь. '.repeat(40).slice(0, AI_ADVICE_MAX_CHARS + 1))).toBe(false);
  });
});
