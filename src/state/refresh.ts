import type { Phase } from './provider';

/**
 * Виден ли спиннер pull-to-refresh.
 *
 * Раньше `refreshing` был жёстко `false`: iOS ни разу не получала «загрузка кончилась»,
 * и после обновления — особенно когда поверх экрана открывался экран загрузки — спиннер
 * оставался висеть над содержимым, пока экран не прокрутят руками. Теперь он привязан
 * к настоящей фазе: виден только пока загрузка идёт и гаснет на ЛЮБОМ её конце —
 * удача (`done`), свежий кэш (`fresh`), обрыв или таймаут (`failed`), покой (`idle`).
 */
export const refreshIndicatorVisible = (phase: Phase): boolean => phase === 'loading';
