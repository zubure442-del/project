/**
 * Обновление жестом «потянуть вниз и отпустить» на вкладках.
 *
 * Нативного RefreshControl больше нет. Его спиннер залипал: жест прерывали переключением вкладки
 * или экраном загрузки поверх, ScrollView не получал конца касания, и растянутый контрол с иконкой
 * висел над содержимым, пока экран не прокрутят руками. Пересоздание контрола по ключу помогало
 * не во всех случаях. Теперь жест читается по отпусканию: экран отпустили, оттянув сверху
 * дальше PULL_REFRESH_DISTANCE, — обновляем. Иконки нет, залипать нечему; ход обновления
 * виден в статусе шапки («Обновляем данные…») или на экране загрузки.
 */

/** На столько точек нужно оттянуть экран вниз от верха, чтобы при отпускании началось обновление. */
export const PULL_REFRESH_DISTANCE = 80;

/** Отпустили экран в этом положении (contentOffset.y; оттянут вниз — отрицательное): обновлять ли. */
export const pulledToRefresh = (offsetY: number): boolean => offsetY <= -PULL_REFRESH_DISTANCE;
