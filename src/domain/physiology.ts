/**
 * Движок физиологии для «Мнения Лиса» (владелец 26.09): модель не умеет считать ряды — физиологию
 * считает код, а YandexGPT только пересказывает готовый вывод.
 *
 * Мнение строится «от главного к причине» (владелец 26.09: «у меня Организм −11 % от нормы, а Лис
 * говорит, что всё нормально»; «зачем мне вечером слушать про сон, если он на этот вечер не повлиял»):
 * 1. Главное — оценка приложения (Организм, Сон), которая сильнее всего ушла от своей нормы, или
 *    отклонение системы сейчас (пульс, стресс, движение, шаги к этому часу, давление, сахар).
 * 2. Что её тянет — составляющая с самым большим вкладом: у Организма те же подоценки, что в самой
 *    оценке (вариабельность, пульс, кислород, давление, сахар), у Сна — длительность, глубокий сон,
 *    пульс во сне. Первое предложение: «Организм ниже нормы: просела вариабельность пульса».
 * 3. Почему — причина из истории кольца, которая правдоподобно объясняет именно эту составляющую
 *    (`CAUSES_FOR` с весами), и объясняет, как связано: «Вчера нагрузка была больше обычной, и тело ещё
 *    восстанавливается». Причины той же системы запрещены (статику не объясняем статикой).
 * Время суток: утром — ночь и восстановление, вечером — день: ночные причины вечером звучат, только если
 * они сильные, а оценку сна вечером Лис не обсуждает. Факты «в норме» больше не звучат: «Пульс покоя как
 * обычно. Вы легли позже обычного» — это случайная статистика, а не мнение.
 * Причины не нашлось — Лис честно говорит, что явной причины кольцо не видит (только для отклонения
 * оценки: о −11 % Организма молчать нельзя). Сказанное в этом цикле не повторяется, пока есть другое.
 *
 * Фразы — простым разговорным языком, без цифр и диагнозов; давление и сахар — «выше обычного», «скачет».
 */

